/* USER CODE BEGIN Header_FSM_Task */
/**
* @brief Function implementing the FSMTaskID thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_FSM_Task */
void FSM_Task(void const * argument)
{
  /* USER CODE BEGIN FSM_Task */
	int ledState = LED_OFF;
  /* Infinite loop */
  for(;;)
  {
	  // Check shared memory
	  switch (ledState) {
		case LED_OFF:
			// 1. read Button state from shared memory
			if (buttonSharedMem == ACT_PUSHED) {
				buttonSharedMem = NO_ACT;
				ledState = LED_ON;
			}
			// 2. write LED_OFF to shared memory
			ledSharedMem = LED_OFF;
			break;
		case LED_ON:
			// 1. read Button state from shared memory
			if (buttonSharedMem == ACT_PUSHED) {
				buttonSharedMem = NO_ACT;
				ledState = LED_OFF;
			}
			// 2. write LED_ON to shared memory
			ledSharedMem = LED_ON;
			break;
	}
    osDelay(10);	// check 10ms
  }
  /* USER CODE END FSM_Task */
}

/* USER CODE BEGIN Header_LED_Task */
/**
* @brief Function implementing the LEDTaskID thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_LED_Task */
void LED_Task(void const * argument)
{
  /* USER CODE BEGIN LED_Task */
	// UART Print
	char msg[50];
	// LCD Print
	LCD_Init(&hi2c1);
	led_state_t prevLedState = LED_OFF;
  /* Infinite loop */
  for(;;)
  {
	  // Read LED info from shared memory
	  if (ledSharedMem == LED_ON) {
		  // led on
		  if (prevLedState == ledSharedMem) continue;
		  prevLedState = ledSharedMem;
		  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_SET);
		  LCD_WriteStringXY(0, 0, "LED ON       ");
		  sprintf(msg, "LED ON\n");
		  HAL_UART_Transmit(&huart2, msg, strlen(msg), 1000);
	  }
	  else {
		  // led off
		  if (prevLedState == ledSharedMem) continue;
		  prevLedState = ledSharedMem;
		  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_RESET);
		  LCD_WriteStringXY(0, 0, "LED OFF       ");
		  sprintf(msg, "LED OFF\n");
		  HAL_UART_Transmit(&huart2, msg, strlen(msg), 1000);
	  }

    osDelay(10);	// 10ms
  }
  /* USER CODE END LED_Task */
}

